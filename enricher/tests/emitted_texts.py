"""Stable fragments of just_dna_enricher emissions, grouped by module in source order.

Each call gets a row, including calls that say the same thing. Give pinned_in only when
the named test asserts the fragment. A named constant may supply the message at the call.
Where messages share wording, context distinguishes their expressions. A CodedWarning whose
formatter supplies the prose can be identified at the call by its literal warning code.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Text:
    module: str
    fragment: str
    pinned_in: str | None = None
    constant: str | None = None
    context: str | None = None

    @property
    def description(self) -> str:
        return self.fragment if self.context is None else f"{self.fragment} (with {self.context!r})"


class Forwarded(Text):
    """No fixed words at the call. Match its entire placeholder or forwarded expression."""


class Carried(Text):
    """An additional historical pin on wording supplied outside a walked message argument."""


